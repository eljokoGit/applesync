# 3. Materialisation
# ---------------------------------------------------------------------------

_FORBIDDEN = '<>:"/\\|?*'
_CSV_HEADER = "album;backup_file;device_source"


def _generated_by_us(root: Path) -> bool:
    """Is this _Albums folder one of ours?

    The marker comes first; failing that, our own albums.csv is proof enough
    (the marker can vanish if a rebuild was interrupted by a locked file,
    typically the CSV left open in a spreadsheet)."""
    if (root / MARKER).exists():
        return True
    csv_file = root / "albums.csv"
    if csv_file.exists():
        try:
            with open(csv_file, encoding="utf-8-sig") as fh:
                return fh.readline().strip() == _CSV_HEADER
        except OSError:
            return False
    return False


def _sanitize(name: str) -> str:
    clean = "".join("_" if c in _FORBIDDEN or ord(c) < 32 else c for c in name)
    clean = clean.strip(" .")
    return clean or "_album"


def _latest_local(manifest: Manifest, rel: str) -> Optional[str]:
    entries = manifest.entries_for_path(rel)
    if not entries:
        return None
    return max(entries, key=lambda e: e.synced_at).local_path


def materialize_albums(
    data: AlbumsData,
    manifest: Manifest,
    dest_root: Path,
    progress_cb: Optional[ProgressCb] = None,   # (files done, files total)
) -> AlbumsReport:
    """(Re)generate `_Albums/`: one folder per album holding COPIES of the
    backup files (ordinary files), plus `_Favorites/` and a summary CSV.

    `_Albums/` is only wiped and rebuilt when it carries the "generated by
    AppleSync" marker — a hand-made folder is never touched."""
    dest_root = Path(dest_root)
    root = dest_root / ALBUMS_DIRNAME
    marker = root / MARKER
    if root.exists():
        if not _generated_by_us(root):
            raise AlbumsError(
                f"{ALBUMS_DIRNAME}/ exists but does not look like a folder "
                f"generated by AppleSync — to be safe, move it or delete it "
                f"yourself, then click \"Albums\" again."
            )
        try:
            shutil.rmtree(root)
        except OSError as e:
            # Locked file (albums.csv open in a spreadsheet?): re-mark the
            # folder as ours for the next attempt, and explain.
            try:
                if root.exists():
                    marker.write_text("generated by AppleSync\n", encoding="utf-8")
            except OSError:
                pass
            raise AlbumsError(
                f"Cannot rebuild {ALBUMS_DIRNAME}/: one of its files is open in "
                f"another program (albums.csv in a spreadsheet?). Close it and "
                f"click \"Albums\" again. Detail: {e}"
            ) from e
    root.mkdir(parents=True)
    marker.write_text(
        "Folder generated by AppleSync (copies of the backup files).\n"
        "Rebuilt on every album recovery: do not store anything here.\n",
        encoding="utf-8",
    )

    report = AlbumsReport(albums_count=len(data.albums),
                          favorites_count=len(data.favorites),
                          library_by_zone=dict(data.library_by_zone))

    def copy_into(folder: Path, rel_local: str) -> int:
        """Copy a backup file into the album folder. Returns bytes written."""
        src = dest_root / rel_local
        base = Path(rel_local).name
        dst = folder / base
        n = 2
        while dst.exists():
            p = Path(base)
            dst = folder / f"{p.stem}.~{n}{p.suffix}"
            n += 1
        shutil.copy2(src, dst)
        return dst.stat().st_size

    groups: list[tuple[str, str, list[str]]] = [
        (title, _sanitize(title), files) for title, files in data.albums
    ]
    groups.append(("Favourites", FAVORITES_DIRNAME, data.favorites))
    expected_total = sum(len(files) for _, _, files in groups)
    done = 0

    csv_path = root / "albums.csv"
    with open(csv_path, "w", newline="", encoding="utf-8-sig") as fh:
        w = csv.writer(fh, delimiter=";")
        w.writerow(["album", "backup_file", "device_source"])

        seen: set[str] = set()
        for title, folder_name, files in groups:
            folder = root / folder_name
            n = 2
            while folder.name in seen:
                folder = root / f"{folder_name}~{n}"
                n += 1
            seen.add(folder.name)
            folder.mkdir(parents=True, exist_ok=True)

            for rel in files:
                done += 1
                if progress_cb:
                    progress_cb(done, expected_total)
                local = _latest_local(manifest, rel)
                if local is None:
                    report.unmatched.append(
                        (title, rel, "never synchronised (run a sync first)")
                    )
                    continue
                if not (dest_root / local).exists():
                    report.unmatched.append(
                        (title, rel, f"absent from disk ({local}) — check the destination")
                    )
                    continue
                w.writerow([title, local, rel])
                report.copied_bytes += copy_into(folder, local)
                report.copies_created += 1

        for asset, reason in data.ignored_assets:
            w.writerow(["(ignored)", "", f"{asset} — {reason}"])

    if data.ignored_assets:
        report.warnings.append(
            f"{len(data.ignored_assets)} database item(s) ignored (outside the "
            f"covered zones) — listed at the end of the CSV."
        )
    report.csv_path = str(csv_path)
    return report


def save_report(report: AlbumsReport, dest_root: Path) -> Path:
    out_dir = Path(dest_root) / ".applesync" / "reports"
    out_dir.mkdir(parents=True, exist_ok=True)
    path = out_dir / f"albums_{time.strftime('%Y%m%d-%H%M%S')}.md"
    path.write_text(report.to_markdown(), encoding="utf-8")
    return path
